"""Build the WoobNav's Japanese fallback atlases (dev tool, not shipped).

WoobNav draws with Kanto Gear's HGSS image fonts (assets/fonts/hgss_*.png), which have Latin
and accents but no kana. This renders the glyphs Japanese needs from Fusion Pixel 8px
(TakWolf, SIL OFL 1.1, the face Kanto Gear itself draws Japanese with) into two LOVE image
fonts the same heights as WoobNav's `small` (11 px) and `label` (14 px) atlases, baseline on
baseline, so art.lua can hand them to Font:setFallbacks (image fonts only take image fonts).

    python tools/woobnav_ja_font/generate.py [path/to/fusion-pixel-8px-proportional-ja.ttf]

The default source is the sibling Kanto Gear checkout. Rerun it after adding a character to
a lang/ file (the glyph set is every kana plus whatever lang/*.lua uses that HGSS lacks).
Writes assets/fonts/ja_small.png, ja_label.png and ja_glyphs.lua.
"""

from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "assets" / "fonts"
DEFAULT = ROOT.parent / "kanto-gear" / "mod" / "kanto_gear" / "fonts" / "ja" / "fusion-pixel-8px-proportional-ja.ttf"
SEP = (255, 0, 255, 255)


def hgss_glyphs() -> str:
    text = (FONTS / "glyphs.lua").read_text(encoding="utf-8")
    start, end = text.index("[=[") + 3, text.rindex("]=]")
    return text[start:end]


def wanted(have: str) -> str:
    chars = [chr(c) for c in range(0x3041, 0x3097)]       # hiragana
    chars += [chr(c) for c in range(0x309B, 0x309D)]      # dakuten marks
    chars += [chr(c) for c in range(0x30A1, 0x30FB)]      # katakana
    chars += list("ー・、。「」『』！？（）：～　")
    for path in sorted((ROOT / "lang").glob("*.lua")):
        chars += [ch for ch in path.read_text(encoding="utf-8") if ord(ch) >= 128]
    have_set = set(have)
    return "".join(ch for ch in dict.fromkeys(chars) if ch not in have_set and ch.isprintable() or ch == "　")


def cells(image: Image.Image) -> list[tuple[int, int]]:
    """Each glyph's columns: runs between separator pixels (the colour at 0, 0) on row 0."""
    sep = image.getpixel((0, 0))
    out, start = [], None
    for x in range(image.width + 1):
        is_sep = x == image.width or image.getpixel((x, 0)) == sep
        if is_sep and start is not None:
            out.append((start, x))
            start = None
        elif not is_sep and start is None:
            start = x
    return out


def baseline(atlas: str, glyphs: str) -> int:
    """The row under the bottom of "H" in an HGSS atlas."""
    image = Image.open(FONTS / atlas).convert("RGBA")
    spans = cells(image)
    left, right = spans[glyphs.index("H")]
    bottom = 0
    for x in range(left, right):
        for y in range(1, image.height):
            if image.getpixel((x, y))[3] > 0:
                bottom = max(bottom, y)
    return bottom + 1


def render(font: ImageFont.FreeTypeFont, value: str, height: int, base: int, output: Path) -> None:
    ascent, _ = font.getmetrics()
    widths = [max(1, round(font.getlength(ch))) for ch in value]
    image = Image.new("RGBA", (sum(widths) + len(value) + 1, height))
    draw = ImageDraw.Draw(image)
    draw.fontmode = "1"  # one bit, as the pixel face is drawn
    x = 0
    for ch, w in zip(value, widths):
        draw.point((x, 0), fill=SEP)
        # the glyph's own pixels never land on the separator row
        draw.text((x + 1, max(1, base - ascent)), ch, font=font, fill=(255, 255, 255, 255))
        x += w + 1
    draw.point((x, 0), fill=SEP)
    image.save(output, optimize=True)


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    font = ImageFont.truetype(str(source), 8, layout_engine=ImageFont.Layout.BASIC)
    have = hgss_glyphs()
    value = wanted(have)
    render(font, value, 11, baseline("hgss_small_font.png", have), FONTS / "ja_small.png")
    render(font, value, 14, baseline("hgss_font.png", have), FONTS / "ja_label.png")
    (FONTS / "ja_glyphs.lua").write_text(
        "-- Generated by tools/woobnav_ja_font/generate.py (Fusion Pixel 8px, SIL OFL 1.1).\n"
        "return [=[" + value + "]=]\n", encoding="utf-8")
    print(f"{len(value)} glyphs")


if __name__ == "__main__":
    main()
